const sourceFiles = ['src/utils/layout.ts', 'src/utils/assets.ts', 'src/models/profilePhoto.ts', 'src/models/createBlock.ts', 'src/store/initialDocument.ts', 'src/utils/documentStorage.ts', 'src/utils/projectStorage.ts', 'src/models/templates.ts', 'src/utils/links.ts', 'src/utils/pagination.ts'];
for (const path of sourceFiles) {
  const source = await readFile(path, 'utf8');
  const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText.replace(/(from\s+['"])(\.\.?\/[^'"]+)(['"])/g, '$1$2.mjs$3');
  const destination = resolve('tmp/check', path.replace(/^src\//, '').replace(/\.ts$/, '.mjs'));
  await mkdir(dirname(destination), { recursive: true });
  await writeFile(destination, output);
}
